// Reference tech vocabulary (annex C, `no-new-skills`): detects a skill that a proposal would add to a
// bullet or a summary without being in its source. A hand-written list of common terms (ADR 0014),
// not copied from any external taxonomy. It only serves detection: a term listed here is never added
// to the library. `ambiguous`: also an ordinary word (Go, Swift, Spring…): compared case-exact, and a
// detection only gives a warning. Zod-free.

export interface TechTerm {
  short: string;
  aliases: string[];
  ambiguous: boolean;
}

const t = (short: string, aliases: string[] = [], ambiguous = false): TechTerm => ({ short, aliases, ambiguous });
const amb = (short: string, aliases: string[] = []): TechTerm => t(short, aliases, true);

